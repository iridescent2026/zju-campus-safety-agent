changed = []
for e in data['entities']:
    eid = e['id']
    if e['kind'] == 'device' and eid in DEVICE:
        title, text = DEVICE[eid]
        e['title'], e['text'] = title, text
        changed.append(('device', eid, title))
    elif e['kind'] == 'zone' and eid in ZONE:
        title, text = ZONE[eid]
        e['title'], e['text'] = title, text
        changed.append(('zone', eid, title))
    elif e['kind'] == 'person' and eid in PERSON:
        role = PERSON[eid]
        e['title'] = role
        e['role'] = role
        e['text'] = f'岗位：{role} · 本地模拟位置，进入危险区域时触发空间报警。'
        changed.append(('person', eid, role))

